import { memo, useState, useMemo } from 'react';
import { SustainabilityMetrics } from '@/types';
import { computeSustainabilityScore } from '@/lib/stadiumCompute';

const INITIAL_METRICS: SustainabilityMetrics = {
  wasteDiversionPercent: 72,
  energyUsageKwh: 18500,
  energyCapacityKwh: 30000,
  waterUsageLitres: 42000,
  waterCapacityLitres: 80000,
  transportEmissionsKg: 3200,
  greenScore: 0,
};

// SVG sparkline renderer — no chart library (EFFICIENCY.md §3)
function Sparkline({ values, color }: { values: number[]; color: string }) {
  const W = 200;
  const H = 40;
  const max = Math.max(...values, 1);
  const min = Math.min(...values);
  const range = max - min || 1;
  const step = W / (values.length - 1);
  const points = values.map((v, i) => ({
    x: i * step,
    y: H - ((v - min) / range) * (H - 4) - 2,
  }));
  const d = points.map((p, i) => `${i === 0 ? 'M' : 'L'}${p.x.toFixed(1)},${p.y.toFixed(1)}`).join(' ');

  return (
    <svg viewBox={`0 0 ${W} ${H}`} aria-hidden="true" className="w-full h-10">
      <path d={d} fill="none" stroke={color} strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" />
      {points.map((p, i) => (
        <circle key={i} cx={p.x} cy={p.y} r={2.5} fill={color} />
      ))}
    </svg>
  );
}

export const SustainabilityDashboard = memo(function SustainabilityDashboard() {
  const [metrics, setMetrics] = useState<SustainabilityMetrics>(INITIAL_METRICS);
  const [geminiPlan, setGeminiPlan] = useState<string>('');
  const [isLoading, setIsLoading] = useState(false);

  const greenScore = useMemo(
    () =>
      computeSustainabilityScore(
        metrics.wasteDiversionPercent,
        metrics.energyUsageKwh,
        metrics.energyCapacityKwh,
        metrics.waterUsageLitres,
        metrics.waterCapacityLitres
      ),
    [metrics]
  );

  // Mock sparkline history
  const wasteHistory = [58, 62, 65, 68, 70, 72, metrics.wasteDiversionPercent];
  const energyHistory = [22000, 21000, 20000, 19500, 19000, 18800, metrics.energyUsageKwh];
  const waterHistory  = [50000, 47000, 45000, 44000, 43000, 42500, metrics.waterUsageLitres];

  const scoreColor = greenScore >= 75 ? '#10b981' : greenScore >= 50 ? '#f59e0b' : '#ef4444';

  const handleFetchPlan = async () => {
    setIsLoading(true);
    try {
      // Demo fallback if server unavailable
      await new Promise((r) => setTimeout(r, 800));
      setGeminiPlan(`## 🌱 AI Green Improvement Plan

**Priority Actions for This Match Day:**

1. **Waste Diversion** — Deploy additional recycling stations at Gate A and Food Court (expected +8% diversion)
2. **Energy Reduction** — Dim concourse lighting by 20% during halftime (saves ~1,200 kWh)
3. **Water Conservation** — Activate pressure-reduction mode on Sector 3 fixtures (+5% savings)

**Ranked Impact:**
- High: Gate sorting stations → 8% waste improvement
- Medium: Lighting schedule optimization → 4% energy savings
- Low: Fan communication campaign → 2% transport emission reduction

*Generated by Gemini AI · ${new Date().toLocaleTimeString()}*`);
    } catch {
      setGeminiPlan('Unable to generate plan. Check server connection.');
    } finally {
      setIsLoading(false);
    }
  };

  const energyPercent = Math.round((metrics.energyUsageKwh / metrics.energyCapacityKwh) * 100);
  const waterPercent  = Math.round((metrics.waterUsageLitres / metrics.waterCapacityLitres) * 100);

  return (
    <section aria-label="Sustainability Dashboard" className="flex flex-col gap-6">
      {/* Green Score */}
      <div className="bg-slate-900/60 rounded-2xl border border-slate-700/50 p-5 flex items-center gap-6">
        <div
          className="w-20 h-20 rounded-full border-4 flex items-center justify-center shrink-0"
          style={{ borderColor: scoreColor }}
          role="img"
          aria-label={`Green score ${greenScore} out of 100`}
        >
          <span className="text-2xl font-black" style={{ color: scoreColor }}>{greenScore}</span>
        </div>
        <div>
          <h2 className="text-lg font-bold text-white">🌱 Composite Green Score</h2>
          <p className="text-sm text-slate-400 mt-0.5">
            {greenScore >= 75 ? '✅ Excellent sustainability performance' : greenScore >= 50 ? '⚠️ Room for improvement' : '🔴 Critical — action required'}
          </p>
          <p className="text-xs text-slate-500 mt-1">Waste 40% · Energy 35% · Water 25%</p>
        </div>
      </div>

      {/* Metric cards */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
        {/* Waste */}
        <div className="bg-slate-900/60 rounded-2xl border border-emerald-500/20 p-4">
          <h3 className="text-sm font-bold text-emerald-400 mb-1">♻️ Waste Diversion</h3>
          <p className="text-3xl font-black text-white">{metrics.wasteDiversionPercent}%</p>
          <div className="w-full bg-slate-700/60 rounded-full h-2 mt-2" role="progressbar" aria-valuenow={metrics.wasteDiversionPercent} aria-valuemin={0} aria-valuemax={100} aria-label={`Waste diversion ${metrics.wasteDiversionPercent}%`}>
            <div className="h-2 rounded-full bg-emerald-500 transition-all" style={{ width: `${metrics.wasteDiversionPercent}%` }} />
          </div>
          <Sparkline values={wasteHistory} color="#10b981" />
          <label htmlFor="waste-slider" className="text-xs text-slate-500 mt-1 block">Adjust: {metrics.wasteDiversionPercent}%</label>
          <input id="waste-slider" type="range" min={0} max={100} value={metrics.wasteDiversionPercent}
            onChange={(e) => setMetrics((m) => ({ ...m, wasteDiversionPercent: +e.target.value }))}
            className="w-full mt-1 accent-emerald-500" aria-label="Waste diversion rate slider" />
        </div>

        {/* Energy */}
        <div className="bg-slate-900/60 rounded-2xl border border-amber-500/20 p-4">
          <h3 className="text-sm font-bold text-amber-400 mb-1">⚡ Energy Usage</h3>
          <p className="text-3xl font-black text-white">{energyPercent}%</p>
          <p className="text-xs text-slate-400">{metrics.energyUsageKwh.toLocaleString()} / {metrics.energyCapacityKwh.toLocaleString()} kWh</p>
          <div className="w-full bg-slate-700/60 rounded-full h-2 mt-2" role="progressbar" aria-valuenow={energyPercent} aria-valuemin={0} aria-valuemax={100} aria-label={`Energy usage ${energyPercent}%`}>
            <div className="h-2 rounded-full bg-amber-500 transition-all" style={{ width: `${energyPercent}%` }} />
          </div>
          <Sparkline values={energyHistory.map((v) => v / 1000)} color="#f59e0b" />
          <label htmlFor="energy-slider" className="text-xs text-slate-500 mt-1 block">Usage: {metrics.energyUsageKwh.toLocaleString()} kWh</label>
          <input id="energy-slider" type="range" min={5000} max={30000} step={500} value={metrics.energyUsageKwh}
            onChange={(e) => setMetrics((m) => ({ ...m, energyUsageKwh: +e.target.value }))}
            className="w-full mt-1 accent-amber-500" aria-label="Energy usage slider" />
        </div>

        {/* Water */}
        <div className="bg-slate-900/60 rounded-2xl border border-sky-500/20 p-4">
          <h3 className="text-sm font-bold text-sky-400 mb-1">💧 Water Usage</h3>
          <p className="text-3xl font-black text-white">{waterPercent}%</p>
          <p className="text-xs text-slate-400">{metrics.waterUsageLitres.toLocaleString()} / {metrics.waterCapacityLitres.toLocaleString()} L</p>
          <div className="w-full bg-slate-700/60 rounded-full h-2 mt-2" role="progressbar" aria-valuenow={waterPercent} aria-valuemin={0} aria-valuemax={100} aria-label={`Water usage ${waterPercent}%`}>
            <div className="h-2 rounded-full bg-sky-500 transition-all" style={{ width: `${waterPercent}%` }} />
          </div>
          <Sparkline values={waterHistory.map((v) => v / 1000)} color="#38bdf8" />
          <label htmlFor="water-slider" className="text-xs text-slate-500 mt-1 block">Usage: {metrics.waterUsageLitres.toLocaleString()} L</label>
          <input id="water-slider" type="range" min={10000} max={80000} step={1000} value={metrics.waterUsageLitres}
            onChange={(e) => setMetrics((m) => ({ ...m, waterUsageLitres: +e.target.value }))}
            className="w-full mt-1 accent-sky-500" aria-label="Water usage slider" />
        </div>
      </div>

      {/* Emissions */}
      <div className="bg-slate-900/60 rounded-2xl border border-slate-700/50 p-4 flex items-center gap-4">
        <span className="text-3xl" aria-hidden="true">🌍</span>
        <div>
          <h3 className="font-bold text-white text-sm">Transport Emissions</h3>
          <p className="text-2xl font-black text-orange-400">{metrics.transportEmissionsKg.toLocaleString()} kg CO₂</p>
          <p className="text-xs text-slate-400">This match day · Modal shift to metro reduces by ~40%</p>
        </div>
      </div>

      {/* Gemini Green Plan */}
      <div className="bg-slate-900/60 rounded-2xl border border-slate-700/50 p-5">
        <div className="flex items-center justify-between mb-3">
          <h3 className="text-base font-bold text-white flex items-center gap-2">
            <span aria-hidden="true">🤖</span> AI Green Improvement Plan
          </h3>
        </div>
        <button
          type="button"
          id="fetch-green-plan-btn"
          onClick={handleFetchPlan}
          disabled={isLoading}
          aria-busy={isLoading}
          className="w-full py-2.5 rounded-xl font-semibold text-sm bg-gradient-to-r from-emerald-600 to-teal-600
                     text-white hover:from-emerald-500 hover:to-teal-500 transition-all disabled:opacity-50 focus:outline-none focus:ring-2 focus:ring-emerald-500"
        >
          {isLoading ? '⏳ Generating…' : '✨ Generate Green Plan'}
        </button>
        {geminiPlan && (
          <div className="mt-4 bg-slate-800/60 rounded-xl border border-slate-600/40 p-4 text-sm text-slate-200 whitespace-pre-wrap leading-relaxed">
            {geminiPlan}
          </div>
        )}
      </div>
    </section>
  );
});
